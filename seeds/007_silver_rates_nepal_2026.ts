export const RATES = CSV.trim()
  .split("\n")
  .slice(1)
  .map((line) => {
    const [date, tola, gram, tenGram] = line.split(",");
    return {
      rate_date: date,
      npr_per_tola: Number(tola),
      npr_per_gram: Number(gram),
      npr_per_10g: Number(tenGram),
    };
  });

export async function seed(knex: Knex): Promise<void> {
  const rows = RATES.map((r) => ({
    rate_date: r.rate_date,
    // silver_rate_reference is laid out for world prices. Only the per-gram
    // and per-tola figures carry over; the per-ounce column holds the same
    // rate per troy ounce (31.1035 g) so it is never a misleading zero.
    npr_per_oz: Math.round(r.npr_per_gram * 31.1035 * 100) / 100,
    npr_per_gram_999: r.npr_per_gram,
    npr_per_tola_999: r.npr_per_tola,
    npr_per_gram_925: Math.round(r.npr_per_gram * 0.925 * 100) / 100,
    source: "fenegosida",
  }));

  // The world-price list this replaces ran 25–35% below the Nepal market. Any
  // of it still in the table is removed, so an old bill is never offered it.
  const removed = await knex("silver_rate_reference").whereNot("source", "fenegosida").del();
  if (removed > 0) console.log(`Removed ${removed} world-price rows`);

  await knex("silver_rate_reference")
    .insert(rows)
    .onConflict("rate_date")
    .merge(["npr_per_oz", "npr_per_gram_999", "npr_per_tola_999", "npr_per_gram_925", "source"]);
  console.log(`Nepal silver rates: ${rows.length} days loaded (1 Jan – 29 Sep 2026)`);
}
